package main

import (
	"database/sql"
	"errors"
	"io/fs"
	"net/http"
	"os"
	"path/filepath"
	"strconv"
	"strings"
)

// libraryHandler answers GET /api/music for a logged-in user: every song in the
// shared library. Anonymous callers are refused with the same two 401 messages as
// GET /api/session, because an open library would let anyone read a name.
//
// Filtering and sorting stay on the client (the library screen does them), so this
// answers the whole library in the order the songs were added — the order the rows
// were inserted, which is what "Hinzugefügt am" sorts by anyway. There is no
// pagination: one user's songs are a few hundred at most, and a page that has to
// ask again would need a second endpoint for nothing gained.
func libraryHandler(db *sql.DB, limiter *rateLimiter) http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		ip := clientIP(r)
		if ok, retry := limiter.allow(ip); !ok {
			w.Header().Set("Retry-After", strconv.Itoa(retry))
			writeError(w, http.StatusTooManyRequests, "too many requests from this address, try again later")
			return
		}

		// The library is shared, so the caller is only checked, not used: any
		// logged-in reader may see every song.
		_, status, message := authenticate(db, r)
		if status != http.StatusOK {
			writeError(w, status, message)
			return
		}

		rows, err := db.Query(`SELECT ` + trackColumns + ` FROM track JOIN user ON user.id = track.user_id ORDER BY track.id`)
		if err != nil {
			writeError(w, http.StatusInternalServerError, "could not load the library")
			return
		}
		defer rows.Close()

		// An empty library answers [], never null: a client must be able to tell an
		// empty library from an answer it could not read.
		tracks := []Track{}
		for rows.Next() {
			track, err := scanTrack(rows)
			if err != nil {
				writeError(w, http.StatusInternalServerError, "could not load the library")
				return
			}
			tracks = append(tracks, track)
		}
		if err := rows.Err(); err != nil {
			writeError(w, http.StatusInternalServerError, "could not load the library")
			return
		}

		writeJSON(w, http.StatusOK, tracks)
	}
}

// trackFileHandler answers GET /api/music/{id} with the stored file for one row.
// This is what the player streams, so the success answer is the file itself —
// the only route here that does not answer the JSON error shape. Errors still do.
//
// ServeFile is used rather than copying the bytes, because it sets Content-Length
// and answers a Range request: a player can start a song before the whole file is
// read. The content type recorded on the row is the one that is sent.
func trackFileHandler(db *sql.DB, library string, limiter *rateLimiter) http.HandlerFunc {
	return func(w http.ResponseWriter, r *http.Request) {
		ip := clientIP(r)
		if ok, retry := limiter.allow(ip); !ok {
			w.Header().Set("Retry-After", strconv.Itoa(retry))
			writeError(w, http.StatusTooManyRequests, "too many requests from this address, try again later")
			return
		}

		// The library is shared, so the caller is only checked, not used: any
		// logged-in reader may see every song.
		_, status, message := authenticate(db, r)
		if status != http.StatusOK {
			writeError(w, status, message)
			return
		}

		id, err := strconv.ParseInt(r.PathValue("id"), 10, 64)
		if err != nil {
			writeError(w, http.StatusBadRequest, "the song id must be a number")
			return
		}

		track, err := trackByID(db, id)
		if errors.Is(err, sql.ErrNoRows) {
			writeError(w, http.StatusNotFound, "no song with that id")
			return
		}
		if err != nil {
			writeError(w, http.StatusInternalServerError, "could not load the song")
			return
		}

		// The stored name is generated by this server, so it cannot escape the
		// folder — but a row written by hand could name something outside it, and
		// that is checked before anything is opened.
		if track.StoredName == "" || strings.ContainsRune(track.StoredName, '/') {
			writeError(w, http.StatusInternalServerError, "the song has no usable file name")
			return
		}
		target := filepath.Join(library, track.StoredName)
		info, err := os.Stat(target)
		if errors.Is(err, fs.ErrNotExist) {
			// The row says the song is there but the file is not, which is the one
			// thing this endpoint cannot serve.
			writeError(w, http.StatusNotFound, "the file for this song is not in the library")
			return
		}
		if err != nil {
			// Something else the file cannot be read as, which is not the caller's fault.
			writeError(w, http.StatusInternalServerError, "could not load the song")
			return
		}
		if !info.Mode().IsRegular() {
			// A name that is not a plain library file, e.g. one written by hand.
			writeError(w, http.StatusInternalServerError, "the song has no usable file name")
			return
		}

		w.Header().Set("Content-Type", track.ContentType)
		w.Header().Set("X-Content-Type-Options", "nosniff")
		w.Header().Set("Accept-Ranges", "bytes")
		w.Header().Set("Content-Disposition", `inline; filename="`+filepath.Base(track.StoredName)+`"`)

		// ServeFile only sniffs a content type when none is set, so the one above is
		// the one that goes out.
		http.ServeFile(w, r, target)
	}
}
